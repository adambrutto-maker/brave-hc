function validPublishedHTOActuals(data){
 if(data?.schema!=='brave-hc-hto-player-actuals/v1'||
    data.status!=='VERIFIED_HTO_CURRENT'||
    data.sourceUrl!=='https://www.htosports.com/teams/default.asp?p=stats&s=hockey&u=BRAVESHOCKEY'||
    !/^W20[0-9]{2}[/][0-9]{2}$/.test(data.season)||
    !Number.isFinite(Date.parse(data.asOf))||
    !Number.isInteger(data.teamGP)||data.teamGP<0||
    !Number.isInteger(data.playerCount)||!Array.isArray(data.players)||
    data.players.length<15||data.playerCount!==data.players.length||
    ![data.teamGoals,data.teamAssists,data.teamPlayerPoints,data.teamGF,data.teamGA].every(
      x=>Number.isInteger(x)&&x>=0)||data.teamGF!==data.teamGoals)return false;
 const names=new Set();
 for(const p of data.players){
  if(typeof p.name!=='string'||!p.name.trim()||names.has(p.name)||
     ![p.gp,p.g,p.a,p.pts].every(x=>Number.isInteger(x)&&x>=0)||
     p.gp>data.teamGP||p.pts!==p.g+p.a)return false;
  names.add(p.name);
 }
 if(data.players.reduce((n,p)=>n+p.g,0)!==data.teamGoals||
    data.players.reduce((n,p)=>n+p.a,0)!==data.teamAssists||
    data.players.reduce((n,p)=>n+p.pts,0)!==data.teamPlayerPoints)return false;
 return true;
}
function renderPublishedHTOActuals(data,minimumTime=-Infinity,season=null){
 if(!validPublishedHTOActuals(data)||
    season!==null&&data.season!==season||
    Date.parse(data.asOf)<=minimumTime)return false;
 const name=identity.name.split(' ').slice(1).join(' ')+', '+identity.name.split(' ')[0];
 const player=data.players.find(p=>p.name.localeCompare(name,'en-CA',{sensitivity:'base'})===0);
 if(!player)return false;
 const cards=[
  detailStat('HTO games played',player.gp),
  detailStat('HTO goals',player.g),
  detailStat('HTO assists',player.a),
  detailStat('HTO points',player.pts)
 ];
 const previous=$('form').previousElementSibling;
 if(previous?.classList?.contains('ph-source'))previous.remove();
 const context=text('p','Official published HTO skater totals only. These are not award decisions. ','ph-source');
 const link=text('a','View official scoring source');
 link.href=data.sourceUrl;link.rel='noopener noreferrer';link.target='_blank';
 context.append(link);
 $('form').before(context);
 $('form').replaceChildren(...cards);
 $('currentSection').hidden=false;
 $('currentSection').setAttribute('aria-label','Verified current HTO skater scoring');
 $('currentSection').querySelector('h2').textContent='Official HTO scoring · '+shortDate(data.asOf);
 $('statsDate').textContent='HTO skater scoring as of '+shortDate(data.asOf)+' · '+data.season;
 return true;
}
function detailStat(label,value,detail){
 const card=statistic(label,value);
 if(detail)card.append(text('div',detail,'ph-detail'));
 return card;
}
function renderCareer(data){
 if(data?.schema!=='brave-hc-player-career-insights/v1'||data.sourceAuthority!=='NATIVE_HTO_PROFILE_STATS_PUBLIC_READBACK')return null;
 const p=data.players?.[String(playerId)];
 if(p?.name!==identity.name||p.status!=='VERIFIED_PROFILE_CAREER_SUM_PARITY')return null;
 const segments=p.segments||[];
 const cards=[];
 for(const segment of segments)for(const high of segment.highs||[]){
  if(!isFiniteNonnegative(high.value)||!Array.isArray(high.seasons))continue;
  cards.push(detailStat(high.label,high.metric==='GAA'?high.value.toFixed(2):high.value,
    high.seasons.join(' · ')));
 }
 if(cards.length){
  $('highsSection').hidden=false;
  $('highs').replaceChildren(...cards);
  $('careerDate').textContent='Career snapshot: '+shortDate(p.capturedAt)+' · ';
 }
 return p;
}
function renderRecords(data){
 if(data?.schema!=='brave-hc-player-record-book/v1'||data.sourceAuthority!=='NATIVE_HTO_RECORDS_PUBLIC_READBACK')return;
 const p=data.players?.[String(playerId)];
 if(p?.name!==identity.name||!p.entries?.length)return;
 $('recordsSection').hidden=false;
 const details=document.createElement('details');
 details.append(text('summary','View '+p.entries.length+' published entries'));
 const list=text('div','','ph-ledger');
 for(const e of newestAchievements(p.entries)){
  if(typeof e.category!=='string'||typeof e.scope!=='string'||typeof e.sourceText!=='string')continue;
  const row=text('article','','ph-record');
  row.append(text('div',e.category+' · '+e.scope,'ph-event-title'),
    text('div',e.sourceText,'ph-event-meta'));
  const urls=Array.isArray(e.sourceURLs)?e.sourceURLs:[];
  const links=text('div','','ph-event-source');
  urls.forEach((value,index)=>{
   try{
    const url=new URL(value);
    if(url.protocol!=='https:'||!['www.htosports.com','htosports.com'].includes(url.hostname)||!/^\d+$/.test(url.searchParams.get('gameID')||''))return;
    const link=text('a',urls.length===1?'Game source ↗':'Game '+(index+1)+' ↗');
    link.href=url.href;link.target='_blank';link.rel='noopener noreferrer';
    if(links.childNodes.length)links.append(' · ');
    links.append(link);
   }catch{}
  });
  if(links.childNodes.length)row.append(links);
  list.append(row);
 }
 details.append(list);
 $('records').replaceChildren(details);
 const a=text('a','Full HTO record book ↗');
 a.href='https://www.htosports.com/teams/default.asp?u=BRAVESHOCKEY&s=hockey&p=records';
 a.target='_blank';a.rel='noopener noreferrer';
 $('recordsSource').replaceChildren(document.createTextNode('Published historical entries · '+shortDate(data.capturedAt)+' · '),a);
}
function renderCurrent(feed,career) {
 if(!validParticipant(feed))return;
 const expected=identity.name.split(' ').slice(1).join(' ')+', '+identity.name.split(' ')[0];
 const candidate=feed.players.find(x=>String(x.name||'').localeCompare(expected,'en-CA',{sensitivity:'base'})===0);
 if(!candidate||candidate.currentHTORaw?.sourceKind!=='OFFICIAL_HTO_PUBLISHED_SEASON_STATISTICS'||candidate.currentHTORaw.season!==feed.season)return;
 const obs=candidate.officialHTOStats,gp=obs?.gp;
 if(!Number.isInteger(gp)||gp<=0)return;
 const stats=[],segment=career?.segments?.find(s=>s.kind===(candidate.position==='Goalie'?'goalie':'skater'));
 const currentSeason='Winter '+feed.season.slice(1,5)+'/20'+feed.season.slice(-2);
 const current=segment?.seasons?.find(s=>s.Season===currentSeason);
 const sameSnapshot=current?.GP===gp&&(candidate.position==='Goalie'?current.GA===obs.goalsAgainst:
   current.G===obs.goals&&current.A===obs.assists&&current.Pts===obs.points);
 const prior=sameSnapshot?(segment?.seasons?.filter(s=>s.Season!==currentSeason)||[]):[];
 const priorGP=prior.reduce((n,s)=>n+(s.GP||0),0);
 if(candidate.position==='Goalie'){
  const ga=obs.goalsAgainst;
  if(!isFiniteNonnegative(ga))return;
  const priorGA=prior.reduce((n,s)=>n+(s.GA||0),0);
  stats.push(detailStat('Snapshot GAA',isFiniteNonnegative(obs.gaa)?obs.gaa.toFixed(2):(ga/gp).toFixed(2),
    priorGP?'Prior career: '+(priorGA/priorGP).toFixed(2)+' GAA':gp+' appearances'));
  if(Number.isInteger(feed.officialTeamGames)&&feed.officialTeamGames>=gp)
   stats.push(detailStat('Share of team games',Math.round(gp/feed.officialTeamGames*100)+'%',gp+' of '+feed.officialTeamGames+' games'));
 }else{
  if(![obs.goals,obs.assists,obs.points].every(isFiniteNonnegative)||obs.goals+obs.assists!==obs.points)return;
  const pace=obs.points/gp;
  const priorPoints=prior.reduce((n,s)=>n+(s.Pts||0),0);
  stats.push(detailStat('Points per game',pace.toFixed(2),priorGP?'Prior career: '+(priorPoints/priorGP).toFixed(2)+' P/GP':gp+' appearances'));
  const teamGoals=feed.verifiedSourceReadback?.team?.goals;
  if(isFiniteNonnegative(teamGoals)&&teamGoals>0&&obs.goals<=teamGoals)
   stats.push(detailStat('Share of team goals',Math.round(obs.goals/teamGoals*100)+'%',obs.goals+' of '+teamGoals+' goals'));
  const pattern=candidate.sourceHTOGamePattern;
  const counts=pattern?.observedCounts;
  if(pattern?.status==='HTO_PER_GAME_OBSERVATIONS_CROSSCHECKED_TO_CURRENT_SEASON'&&pattern.season===feed.season&&counts?.gamesPlayed===gp&&Number.isInteger(counts.pointScoringGames)&&counts.pointScoringGames>=0&&counts.pointScoringGames<=gp)
   stats.push(detailStat('Games with a point',counts.pointScoringGames+'/'+gp,Math.round(counts.pointScoringGames/gp*100)+'% of appearances'));
 }
 if(!stats.length)return;
 $('currentSection').hidden=false;
 $('currentSection').setAttribute('aria-label','Dated season snapshot');
 $('currentSection').querySelector('h2').textContent='Season snapshot · '+shortDate(feed.sourceReference.htoReadback);
 const previousContext=$('form').previousElementSibling;
 if(previousContext?.classList?.contains('ph-source'))previousContext.remove();
 const context=text('p','These figures use a separate historical snapshot. ','ph-source');
 const bio=text('a','View Bio statistics ↗');
 bio.href='./player-bio.html?playerID='+playerId+'&embed=1';
 bio.target='_blank';bio.rel='noopener noreferrer';context.append(bio);
 $('form').before(context);
 $('form').replaceChildren(...stats);
 $('statsDate').textContent='Stats snapshot: '+shortDate(feed.sourceReference.htoReadback)+' · '+feed.season;
}
(async()=>{
 if(!identity){setNotice('Player identity requires verification.');return;}
 const resources=[
 ['player-highlights-ledger.json',validLedger],
 ['awards-participants.json',x=>x],
 ['player-career-insights.json',x=>x],
 ['player-record-book.json',x=>x],
 ['player-highlights-display-corrections.json',validDisplayCorrections],
 ['player-actuals.json',x=>x],
 ['player-actuals-hourly.json',x=>x]
 ];
 const results=await Promise.allSettled(resources.map(([file,validate])=>fetch(root+file,{cache:'no-store'}).then(async r=>{
  if(!r.ok)throw Error(file+' HTTP '+r.status);return validate(await r.json());
 })));
 const [legacyResult,feedResult,careerResult,recordsResult,correctionsResult,actualResult,hourlyResult]=results;
 try{
  const check=await fetch(root+'assets/approved/source-manifest.json',{cache:'no-store'});
  if(check.ok)approvedArtworkReady=validApprovedArtwork(await check.json());
 }catch{/* Missing release assets safely retain the previously verified artwork. */}

 let career=null;
 if(careerResult.status==='fulfilled')career=renderCareer(careerResult.value);
 if(recordsResult.status==='fulfilled')renderRecords(recordsResult.value);
 if(legacyResult.status==='fulfilled'){
  const ledger=legacyResult.value,record=ledger.players[String(playerId)];
  if(record&&(record.name!==identity.name||!record.profileUrl.endsWith('playerID='+playerId)))warnings.push('Career highlights unavailable');
  else if(!record?.items.length||!correctedPlayerIds.has(String(playerId)))renderLegacy(record,ledger.capturedAt);
  else if(correctionsResult.status==='fulfilled'){
   try{renderLegacy(correctedLegacyDisplay(record,correctionsResult.value),ledger.capturedAt);}
   catch{warnings.push('Career highlights temporarily unavailable');}
  }else warnings.push('Career highlights temporarily unavailable');
 }else warnings.push('Career highlights unavailable');
 let latestParticipant=feedResult.status==='fulfilled'&&validParticipant(feedResult.value)?feedResult.value:null;
 if(latestParticipant)renderCurrent(latestParticipant,career);
 let displayedTime=latestParticipant?Date.parse(latestParticipant.sourceReference.htoReadback):-Infinity;
 const actualChoices=[actualResult,hourlyResult].filter(r=>r.status==='fulfilled'&&
   validPublishedHTOActuals(r.value)).map(r=>r.value).sort((a,b)=>Date.parse(b.asOf)-Date.parse(a.asOf));
 let latestActual=actualChoices[0]||null;
 if(latestActual&&renderPublishedHTOActuals(latestActual,displayedTime,latestParticipant?.season||null))
  displayedTime=Date.parse(latestActual.asOf);
 // Source-aware hourly refresh: select the newest independently verified public feed
 // rather than repeatedly displaying a stale participant/award snapshot.
 if(typeof window.setInterval==='function'&&(latestParticipant||latestActual)){
  let inflight=false;
  window.setInterval(async()=>{
   if(inflight||document.hidden)return;
   inflight=true;
   try{
    const feeds=await Promise.allSettled(
      ['awards-participants.json','player-actuals.json','player-actuals-hourly.json'].map(async file=>{
       const resp=await fetch(root+file,{cache:'no-store'});
       if(!resp.ok)throw Error(file+' HTTP '+resp.status);
       return await resp.json();
      }));
    const opportunities=[];
    if(feeds[0].status==='fulfilled'){
     const next=feeds[0].value;
     if(validParticipant(next)&&
       (!latestParticipant||next.season!==latestParticipant.season||
        next.officialTeamGames>=latestParticipant.officialTeamGames)&&
       Date.parse(next.sourceReference.htoReadback)>displayedTime){
      opportunities.push({time:Date.parse(next.sourceReference.htoReadback),kind:'participant',value:next});
     }
    }
    for(const feed of feeds.slice(1)){
     if(feed.status!=='fulfilled')continue;
     const next=feed.value;
     if(validPublishedHTOActuals(next)&&
       (!latestActual||next.season!==latestActual.season||
        next.teamGP>=latestActual.teamGP)&&
       Date.parse(next.asOf)>displayedTime)
      opportunities.push({time:Date.parse(next.asOf),kind:'actual',value:next});
    }
    opportunities.sort((a,b)=>b.time-a.time);
    for(const next of opportunities){
     if(next.kind==='actual'){
      if(renderPublishedHTOActuals(next.value,displayedTime,
          latestParticipant?.season||latestActual?.season||null)){
       latestActual=next.value;displayedTime=next.time;break;
      }
     }else{
      const wanted=identity.name.split(' ').slice(1).join(' ')+', '+identity.name.split(' ')[0];
      if(next.value.players.some(p=>String(p.name||'').localeCompare(wanted,'en-CA',
         {sensitivity:'base'})===0)){
       renderCurrent(next.value,career);
       latestParticipant=next.value;displayedTime=next.time;break;
      }
     }
    }
   }catch(e){console.warn('Verified current-season refresh skipped',e);}
   finally{inflight=false;}
  },3600000);
 }
 // Auto-refresh existing player iframe when the authoritative verified ledger
 // gets a new readback. Never create a winner from derived/stale stats.
 if(legacyResult.status==='fulfilled' && typeof window.setInterval==='function'){
  let fingerprint=JSON.stringify(legacyResult.value.players[String(playerId)]?.items||[]);
  let inflight=false;
  window.setInterval(async()=>{
   if(inflight||document.hidden)return;
   inflight=true;
   try{
    const response=await fetch(root+'player-highlights-ledger.json',{cache:'no-store'});
    if(!response.ok)return;
    const fresh=validLedger(await response.json());
    const next=fresh.players[String(playerId)];
    if(!next||next.name!==identity.name||
       !next.profileUrl.endsWith('playerID='+playerId))return;
    const value=JSON.stringify(next.items);
    if(value===fingerprint)return;
    if(correctedPlayerIds.has(String(playerId))){
      if(correctionsResult.status!=='fulfilled')return;
      renderLegacy(correctedLegacyDisplay(next,correctionsResult.value),fresh.capturedAt);
    }else renderLegacy(next,fresh.capturedAt);
    fingerprint=value;
   }catch(e){console.warn('Verified highlight refresh skipped',e);}
   finally{inflight=false;}
  },180000);
 }
 const source=publicProfileLink();
 if(source){source.textContent='Full HTO profile ↗';$('profileSource').append(source);}
 $('notice').hidden=!warnings.length;
 setNotice(warnings.join(' · '));
})();
